import { getNodePorts, getFunctionDataInputs, DATA_OPERATORS, LOGIC_GATES, isFunctionNode, isControlEdge } from '../data/node-types';
import { emitFunctionDeclaration } from './function-language';

export const EXPORT_LANGUAGES = [
  { id: 'javascript', name: 'JavaScript', extension: 'js' },
  { id: 'typescript', name: 'TypeScript', extension: 'ts' },
  { id: 'python', name: 'Python', extension: 'py' },
];

/** Compiles a deliberately documented expression subset. Invalid user code
 * throws rather than silently emitting null/TODO instead of authored logic.
 */
export function generateCode(graph, language) {
  if (!EXPORT_LANGUAGES.some(l => l.id === language)) throw new Error('Unsupported export language');
  const py = language === 'python', ts = language === 'typescript';
  const nodes = new Map(graph.nodes.map(n => [n.id, n]));
  const incoming = new Map(graph.edges.map(e => [`${e.target}:${e.targetPort}`, e]));
  const q = str => JSON.stringify(String(str));
  const nil = py ? 'None' : 'null';
  const yes = py ? 'True' : 'true';
  const no = py ? 'False' : 'false';
  const quote = str => str === null ? nil : q(str);
  const call = (name, args) => `${name}(${args.join(', ')})`;
  const src = (node, port) => {
    const edge = incoming.get(`${node.id}:${port}`);
    if (!edge) return nil;
    const inputPort = getNodePorts(node).inputs.find(p => p.id === port);
    const expected = inputPort?.kind === 'boolean' ? 'boolean' : inputPort?.dataType || 'any';
    return `checked(read(${q(edge.source)}, ${q(edge.sourcePort)}), ${q(expected)})`;
  };
  const next = (node, port) => graph.edges.find(e => e.source === node.id && e.sourcePort === port && isControlEdge(graph, e))?.target || null;
  const flowTriggered = graph.nodes.filter(isFunctionNode).filter(fn => graph.edges.some(e => {
    if (e.target !== fn.id || e.targetPort !== 'execute') return false;
    const upstream = nodes.get(e.source);
    return upstream && getNodePorts(upstream).outputs.find(p => p.id === e.sourcePort)?.kind === 'flow';
  })).map(fn => fn.id);
  const functions = graph.nodes.filter(isFunctionNode).map(node => ({ node, ...emitFunctionDeclaration(node, language, getFunctionDataInputs(node).length, getNodePorts(node).outputs.filter(p => p.id !== 'done').length) }));
  const functionsById = new Map(functions.map(fn => [fn.node.id, fn]));
  const signal = (node, port) => {
    if (node.type === 'boolean') return node.value ? yes : no;
    if (node.type === 'variable') return typeof node.dataValue === 'string' ? JSON.stringify(node.dataValue) : typeof node.dataValue === 'boolean' ? (node.dataValue ? yes : no) : String(node.dataValue);
    if (node.type === 'not') return call('tri_not', [src(node, 'a')]);
    if (LOGIC_GATES.includes(node.type)) return call(`tri_${node.type}`, getNodePorts(node).inputs.map(p => src(node, p.id)));
    if (node.type === 'compare') return call('tri_compare', [src(node, 'a'), src(node, 'b'), q(node.comparison || '==')]);
    if (DATA_OPERATORS.includes(node.type)) return call('data_operator', [q(node.type), src(node, 'a'), node.type === 'negate' ? nil : src(node, 'b')]);
    if (node.type === 'output' || node.type === 'watch') return src(node, 'in');
    if (node.type === 'assert') return call('assert_value', [src(node, 'in'), q(node.check || 'range'), String(node.min ?? 0), String(node.max ?? 100), q(node.expected ?? 'true'), q(node.expectedType ?? 'number')]);
    if (isFunctionNode(node)) {
      const fn = functionsById.get(node.id);
      const type = port === 'done' ? 'boolean' : (node.portTypes || {})[port] || 'any';
      const trigger = (node.triggerMode || 'auto') === 'auto' ? yes
        : flowTriggered.includes(node.id) ? (py ? `(${q(node.id)} in control_active)` : `controlActive.has(${q(node.id)})`)
        : src(node, 'execute');
      const args = fn.parsed.inputs.map(k => src(node, k)).join(', ');
      // invoke_function memoizes one actual call per Function node. DONE is
      // FALSE unless EXEC is TRUE and the portable body returns successfully.
      const thunk = py ? `lambda: ${fn.name}(${args})` : `() => ${fn.name}(${args})`;
      const expression = `invoke_function(${q(node.id)}, ${trigger}, ${thunk})[${q(port)}]`;
      return `checked(${expression}, ${q(type)})`;
    }
    return nil;
  };
  const cases = [];
  graph.nodes.forEach(node => {
    const ports = node.type === 'output' ? [{ id: 'out' }] : getNodePorts(node).outputs.filter(p => p.kind !== 'flow');
    ports.forEach(port => cases.push({ key: `${node.id}:${port.id}`, expr: signal(node, port.id) }));
  });
  const starts = graph.nodes.filter(n => n.type === 'start').map(n => n.id);
  const flowNodes = graph.nodes.filter(n => ['start', 'process', 'conditional', 'end'].includes(n.type) || isFunctionNode(n));
  if (py) {
    const lines = [
      '# Generated by Nexa Flow — typed data + real Function definitions',
      'import math',
      '# Limited expression subset, NOT arbitrary source translation.',
      '# Review generated code before production deployment.', '',
      'def checked(value, data_type):',
      '    if value is None or data_type == "any": return value',
      '    if data_type == "boolean": return value if isinstance(value, bool) else None',
      '    if data_type == "number": return value if isinstance(value, (int, float)) and not isinstance(value, bool) else None',
      '    if data_type == "string": return value if isinstance(value, str) else None',
      '    return None', '',
      'def assert_value(value, mode, minimum, maximum, expected, expected_type):',
      '    ok = True',
      '    if mode == "range": ok = isinstance(value, (int, float)) and not isinstance(value, bool) and minimum <= value <= maximum',
      '    elif mode == "type": ok = (isinstance(value, bool) if expected_type == "boolean" else isinstance(value, str) if expected_type == "string" else isinstance(value, (int, float)) and not isinstance(value, bool))',
      '    elif mode == "equals":',
      '        wanted = True if expected == "true" else False if expected == "false" else None if expected == "null" else expected',
      '        try: wanted = float(expected) if expected not in ("true", "false", "null", "") else wanted',
      '        except ValueError: pass',
      '        ok = type(value) is type(wanted) and value == wanted or isinstance(value, (int, float)) and not isinstance(value, bool) and type(wanted) is float and value == wanted',
      '    if not ok: raise AssertionError("Nexa Flow assertion failed")',
      '    return value', '',
      'def tri_and(*v):', '    return False if any(x is False for x in v) else True if v and all(x is True for x in v) else None', '',
      'def tri_or(*v):', '    return True if any(x is True for x in v) else False if v and all(x is False for x in v) else None', '',
      'def tri_not(v):', '    return None if not isinstance(v, bool) else not v', '',
      'def tri_xor(*v):', '    return None if not v or any(not isinstance(x, bool) for x in v) else sum(x is True for x in v) % 2 == 1', '',
      'def tri_nand(*v):', '    return tri_not(tri_and(*v))', '',
      'def tri_nor(*v):', '    return tri_not(tri_or(*v))', '',
      'def tri_xnor(*v):', '    return tri_not(tri_xor(*v))', '',
      'def tri_compare(a, b, operator):',
      '    if a is None or b is None:', '        return None',
      '    if operator == "==": return ((isinstance(a, (int, float)) and not isinstance(a, bool) and isinstance(b, (int, float)) and not isinstance(b, bool)) or type(a) is type(b)) and a == b',
      '    if operator == "!=": return not (((isinstance(a, (int, float)) and not isinstance(a, bool) and isinstance(b, (int, float)) and not isinstance(b, bool)) or type(a) is type(b)) and a == b)',
      '    valid_numbers = isinstance(a, (int, float)) and not isinstance(a, bool) and isinstance(b, (int, float)) and not isinstance(b, bool)',
      '    valid_strings = isinstance(a, str) and isinstance(b, str)',
      '    if not (valid_numbers or valid_strings): return None',
      '    if operator == ">": return a > b', '    if operator == ">=": return a >= b',
      '    if operator == "<": return a < b', '    if operator == "<=": return a <= b',
      '    return None', '',
      'def data_operator(op, a, b=None):',
      '    if op == "concat": return a + b if isinstance(a, str) and isinstance(b, str) else None',
      '    if not (type(a) in (int, float) and (op == "negate" or type(b) in (int, float))): return None',
      '    if op in ("divide", "modulo") and b == 0: return None',
      '    try:',
      '        result = {"add": lambda: a+b, "subtract": lambda: a-b, "multiply": lambda: a*b, "divide": lambda: a/b, "modulo": lambda: a%b, "power": lambda: a**b, "negate": lambda: -a}.get(op, lambda: None)()',
      '        return result if isinstance(result, (int, float)) and not isinstance(result, bool) and math.isfinite(result) else None',
      '    except (ArithmeticError, OverflowError, TypeError, ValueError): return None', '',
      `_flow_triggered = set(${JSON.stringify(flowTriggered)})`,
      'control_active = set()',
      '_function_cache = {}',
      'def invoke_function(node_id, trigger, thunk):',
      '    if node_id in _function_cache: return _function_cache[node_id]',
      '    result = {"done": False}',
      '    if trigger is True:',
      '        try:',
      '            result.update(thunk())',
      '            result["done"] = True',
      '        except Exception as error:',
      '            print(f"Nexa Flow: function {node_id} failed: {error}")',
      '    _function_cache[node_id] = result',
      '    return result', '',
      ...functions.flatMap(fn => [`# Function node: ${fn.node.title.replace(/[\r\n]/g, ' ').slice(0, 75)} (${fn.node.language} subset)`, fn.source, '']),
      'cache = {}', 'visiting = set()',
      'def read(node_id, port="out"):',
      '    if node_id in _flow_triggered and node_id not in control_active: return False if port == "done" else None',
      '    key = f"{node_id}:{port}"',
      '    if key in cache: return cache[key]',
      '    if key in visiting: raise RuntimeError("Cyclic data dependency")',
      '    visiting.add(key)',
    ];
    cases.forEach((item, index) => lines.push(`    ${index ? 'elif' : 'if'} key == ${q(item.key)}:`, `        result = ${item.expr}`));
    if (cases.length) lines.push('    else:', `        result = ${nil}`);
    else lines.push(`    result = ${nil}`);
    lines.push('    visiting.remove(key)', '    cache[key] = result', '    return result', '',
      'def run_flow():', '    # Process actions are intentionally TODO placeholders.',
      `    for entry in ${JSON.stringify(starts)}:`, '        current = entry', '        visited = set()',
      '        for _ in range(500):', '            if current is None: break',
      '            if current in visited: raise RuntimeError("Flow loop detected")',
      '            visited.add(current)');
    flowNodes.forEach((node, index) => {
      lines.push(`            ${index ? 'elif' : 'if'} current == ${q(node.id)}:`, `                # ${node.title.replace(/[\r\n]/g, ' ').slice(0, 75)}`);
      if (node.type === 'conditional') {
        const expr = call(`tri_${node.conditionMode || 'and'}`, getNodePorts(node).inputs.filter(p => p.kind !== 'flow').map(p => src(node, p.id)));
        lines.push(`                choice = ${expr}`, '                if choice is None: raise RuntimeError("Unresolved decision")', `                current = ${quote(next(node, 'true'))} if choice else ${quote(next(node, 'false'))}`);
      } else if (node.type === 'end') lines.push('                current = None');
      else if (isFunctionNode(node)) {
        lines.push(`                control_active.add(${q(node.id)})`, `                finished = read(${q(node.id)}, "done")`,
          `                current = ${quote(next(node, 'done'))} if finished is True else None`);
      }
      else { if (node.type === 'process') lines.push('                # TODO: implement application process'); lines.push(`                current = ${quote(next(node, 'out'))}`); }
    });
    if (flowNodes.length) lines.push('            else:', '                break');
    else lines.push('            break');
    lines.push('', 'if __name__ == "__main__":', '    run_flow()', '');
    return lines.join('\n');
  }
  const lines = [
    `// Generated by Nexa Flow — ${language === 'typescript' ? 'TypeScript' : 'JavaScript'}`,
    '// Limited expression subset, NOT arbitrary source translation.',
    '// Review generated code before production deployment.', '',
    `const checked = (value${ts ? ': any' : ''}, dataType${ts ? ': string' : ''}) => value == null || dataType === 'any' || typeof value === dataType ? value : null;`,
    `function assert_value(value${ts ? ': any' : ''}, mode${ts ? ': string' : ''}, minimum${ts ? ': number' : ''}, maximum${ts ? ': number' : ''}, expected${ts ? ': string' : ''}, expectedType${ts ? ': string' : ''}) {`,
    '  let ok = true;',
    '  if (mode === "range") ok = typeof value === "number" && value >= minimum && value <= maximum;',
    '  else if (mode === "type") ok = typeof value === expectedType;',
    '  else if (mode === "equals") { const wanted = expected === "true" ? true : expected === "false" ? false : expected === "null" ? null : expected.trim() && Number.isFinite(Number(expected)) ? Number(expected) : expected; ok = value === wanted; }',
    '  if (!ok) throw new Error("Nexa Flow assertion failed");',
    '  return value;', '}',
    `const tri_and = (...v${ts ? ': any[]' : ''}) => v.includes(false) ? false : v.length > 0 && v.every(x => x === true) ? true : null;`,
    `const tri_or = (...v${ts ? ': any[]' : ''}) => v.includes(true) ? true : v.length > 0 && v.every(x => x === false) ? false : null;`,
    `const tri_not = (v${ts ? ': any' : ''}) => typeof v === "boolean" ? !v : null;`,
    `const tri_xor = (...v${ts ? ': any[]' : ''}) => !v.length || v.some(x => typeof x !== "boolean") ? null : v.filter(x => x).length % 2 === 1;`,
    `const tri_nand = (...v${ts ? ': any[]' : ''}) => tri_not(tri_and(...v));`,
    `const tri_nor = (...v${ts ? ': any[]' : ''}) => tri_not(tri_or(...v));`,
    `const tri_xnor = (...v${ts ? ': any[]' : ''}) => tri_not(tri_xor(...v));`,
    `const tri_compare = (a${ts ? ': any' : ''}, b${ts ? ': any' : ''}, op${ts ? ': string' : ''}) => {`,
    '  if (a == null || b == null) return null;',
    '  if (op === "==") return a === b;',
    '  if (op === "!=") return a !== b;',
    '  if (typeof a !== typeof b || !["number", "string"].includes(typeof a)) return null;',
    '  if (op === ">") return a > b;', '  if (op === ">=") return a >= b;',
    '  if (op === "<") return a < b;', '  if (op === "<=") return a <= b;',
    '  return null;', '};', '',
    `function data_operator(op${ts ? ': string' : ''}, a${ts ? ': any' : ''}, b${ts ? ': any' : ''} = null)${ts ? ': any' : ''} {`,
    '  if (op === "concat") return typeof a === "string" && typeof b === "string" ? a + b : null;',
    '  if (typeof a !== "number" || !Number.isFinite(a) || (op !== "negate" && (typeof b !== "number" || !Number.isFinite(b)))) return null;',
    '  if ((op === "divide" || op === "modulo") && b === 0) return null;',
    '  const result = op === "add" ? a + b : op === "subtract" ? a - b : op === "multiply" ? a * b : op === "divide" ? a / b : op === "modulo" ? a % b : op === "power" ? a ** b : op === "negate" ? -a : null;',
    '  return typeof result === "number" && Number.isFinite(result) ? result : null;',
    '}',
    `const flowTriggered = new Set(${JSON.stringify(flowTriggered)});`,
    'const controlActive = new Set();',
    `const functionCache${ts ? ': Map<string, any>' : ''} = new Map();`,
    `function invoke_function(nodeId${ts ? ': string' : ''}, trigger${ts ? ': any' : ''}, thunk${ts ? ': () => any' : ''})${ts ? ': any' : ''} {`,
    '  if (functionCache.has(nodeId)) return functionCache.get(nodeId);',
    '  let result = { done: false };',
    '  if (trigger === true) {',
    '    try { result = { ...thunk(), done: true }; }',
    '    catch (error) { console.warn("Nexa Flow function failed", nodeId, error); }',
    '  }',
    '  functionCache.set(nodeId, result);',
    '  return result;',
    '}', '',
    ...functions.flatMap(fn => [`// Function node: ${fn.node.title.replace(/[\r\n]/g, ' ').slice(0, 75)} (${fn.node.language} subset)`, fn.source, '']),
    'const cache = new Map();', 'const visiting = new Set();',
    `function read(nodeId${ts ? ': string' : ''}, port${ts ? ': string' : ''} = "out")${ts ? ': any' : ''} {`,
    '  if (flowTriggered.has(nodeId) && !controlActive.has(nodeId)) return port === "done" ? false : null;',
    '  const key = `${nodeId}:${port}`;',
    '  if (cache.has(key)) return cache.get(key);',
    '  if (visiting.has(key)) throw new Error("Cyclic data dependency");',
    '  visiting.add(key);', `  let result${ts ? ': any' : ''} = null;`, '  switch (key) {',
  ];
  cases.forEach(item => lines.push(`    case ${q(item.key)}: result = ${item.expr}; break;`));
  lines.push('    default: break;', '  }', '  visiting.delete(key);', '  cache.set(key, result);', '  return result;', '}', '',
    'function runFlow() {', `  for (const entry of ${JSON.stringify(starts)}) {`,
    `    let current${ts ? ': string | null' : ''} = entry;`, '    const visited = new Set();',
    '    for (let step = 0; current !== null && step < 500; step++) {',
    '      if (visited.has(current)) throw new Error("Flow loop detected");',
    '      visited.add(current);', '      switch (current) {');
  flowNodes.forEach(node => {
    lines.push(`        case ${q(node.id)}: {`, `          // ${node.title.replace(/[\r\n]/g, ' ').slice(0, 75)}`);
    if (node.type === 'conditional') {
      const expr = call(`tri_${node.conditionMode || 'and'}`, getNodePorts(node).inputs.filter(p => p.kind !== 'flow').map(p => src(node, p.id)));
      lines.push(`          const choice = ${expr};`, '          if (choice === null) throw new Error("Unresolved decision");', `          current = choice ? ${quote(next(node, 'true'))} : ${quote(next(node, 'false'))};`);
    } else if (node.type === 'end') lines.push('          current = null;');
    else if (isFunctionNode(node)) {
      lines.push(`          controlActive.add(${q(node.id)});`, `          const finished = read(${q(node.id)}, "done");`,
        `          current = finished === true ? ${quote(next(node, 'done'))} : null;`);
    }
    else { if (node.type === 'process') lines.push('          // TODO: implement application process'); lines.push(`          current = ${quote(next(node, 'out'))};`); }
    lines.push('          break;', '        }');
  });
  lines.push('        default: current = null; break;', '      }', '    }', '  }', '}', '', 'runFlow();', '');
  return lines.join('\n');
}
